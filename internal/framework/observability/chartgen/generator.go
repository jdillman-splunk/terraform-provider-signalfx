// The chart generator turns every charts/schemas/*.yml chart schema into
// compiling Go that lives in its own package
// (internal/framework/observability/charts), separate from the hand-written
// dashboard package that imports it: one file per chart, a stable content
// registry, and a generated dashboard transport bridge. runGeneration is the
// entrypoint used by both write and non-mutating check modes. This is what
// makes the "schema files are build-time, not
// runtime" property real - nothing in the provider parses YAML at
// `terraform plan` time; the generated output gets committed and compiled
// in.
//
// The supported DSL covers scalar and enum properties, reversible negate and
// relative-duration transforms, list/map/block/oneof nested attributes, and
// array wrapping. Any future shape outside that explicit set fails generation
// rather than silently dropping a constraint.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	supportSchemaVersion      = 1
	chartGeneratorPath        = "internal/framework/observability/chartgen"
	chartSchemasPath          = "internal/framework/observability/charts/schemas"
	generatedCodeMarker       = "Code generated by " + chartGeneratorPath
	legacyGeneratedCodeMarker = "Code generated by internal/chartgen"
)

// --- YAML shape -------------------------------------------------------
//
// Mirrors charts/schemas/*.yml directly.

type chartSchema struct {
	Type string `yaml:"type"`

	// Version must exactly match supportSchemaVersion on a chart root. The
	// generator rejects both missing/zero and future versions so it can never
	// silently interpret a newer DSL with older semantics.
	Version int `yaml:"version"`

	Description    string              `yaml:"description"`
	Dashify        dashifyElement      `yaml:"dashify"`
	Extends        []string            `yaml:"extends"`
	Properties     map[string]property `yaml:"properties"`
	Normalizations []normalization     `yaml:"normalizations"`
}

type normalization struct {
	Kind   string   `yaml:"kind"`
	Target []string `yaml:"target"`
	Source []string `yaml:"source"`
	Unit   []string `yaml:"unit"`
	Prefix []string `yaml:"prefix"`
	Suffix []string `yaml:"suffix"`
}

type valueCondition struct {
	Field string `yaml:"field"`
	Value string `yaml:"value"`
}

func (c *valueCondition) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("value condition must be a mapping, got YAML kind %d", node.Kind)
	}
	if _, err := mappingPresence(node, map[string]bool{"field": true, "value": true}, "valueCondition"); err != nil {
		return err
	}
	type plainCondition valueCondition
	var decoded plainCondition
	if err := node.Decode(&decoded); err != nil {
		return err
	}
	*c = valueCondition(decoded)
	return nil
}

type dashifyElement struct {
	Element dashifyElementDefinition `yaml:"element"`
}

type dashifyElementDefinition struct {
	Name string `yaml:"name"`
	// Args is the element tag's value in the serialized document - the
	// `[]any{}` that BuildSpec seeds. Only an explicitly authored empty list
	// is supported; omission must not silently mean the same thing.
	Args        []any `yaml:"args"`
	argsPresent bool  `yaml:"-"`
}

func (e *dashifyElementDefinition) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("dashify element must be a mapping, got YAML kind %d", node.Kind)
	}
	present, err := mappingPresence(node, map[string]bool{"name": true, "args": true}, "dashifyElementDefinition")
	if err != nil {
		return err
	}
	type plainElement dashifyElementDefinition
	var decoded plainElement
	if err := node.Decode(&decoded); err != nil {
		return err
	}
	*e = dashifyElementDefinition(decoded)
	e.argsPresent = present["args"]
	return nil
}

type property struct {
	Type string `yaml:"type"` // string | bool | number | float | enum | list | map | block | oneof

	// Description is required on every property (chartgen fails generation
	// otherwise, see requireDescriptions) and becomes the generated
	// attribute's MarkdownDescription. A property that reaches its final
	// shape only through `ref` inherits the referenced property's
	// description unless it sets its own, via the same overlay rule as any
	// other field.
	Description string `yaml:"description"`

	// Ref inherits another property's whole shape: "<file>#<propertyName>".
	// Keys set alongside the ref win over the inherited ones, so a nested use
	// can reuse a common/ shape while supplying its own mapping.path.
	// `extends` is the root-level equivalent; `ref` is what makes a shape
	// reusable at an arbitrary nesting depth.
	Ref string `yaml:"ref"`

	Optional bool     `yaml:"optional"`
	Required bool     `yaml:"required"`
	Values   []string `yaml:"values"` // enum

	// Default is the value Dashify itself falls back to when the field is
	// absent from the document. It is rendered into the attribute's
	// MarkdownDescription and deliberately NOT emitted as a
	// terraform-plugin-framework Default: a framework default would need
	// Computed: true and would make the provider write a field the
	// practitioner never set, which would break the byte-for-byte document
	// round-trip the fixture tests require.
	Default any `yaml:"default"`

	// Min and Max bound a `number` property; anywhere else they are a
	// generation error (see requireEnforceableBounds) rather than a constraint
	// that looks declared but isn't.
	Min           *int            `yaml:"min"`
	Max           *int            `yaml:"max"`
	MinLength     *int            `yaml:"min_length"`
	ConflictsWith []string        `yaml:"conflicts_with"`
	AtLeastOneOf  []string        `yaml:"at_least_one_of"`
	RequiresValue *valueCondition `yaml:"requires_value"`
	RequiredWhen  *valueCondition `yaml:"required_when"`

	Mapping    propertyMapping     `yaml:"mapping"`
	Item       *itemSchema         `yaml:"item"`       // list | map
	Properties map[string]property `yaml:"properties"` // block
	Variants   map[string]property `yaml:"variants"`   // oneof
	MinItems   *int                `yaml:"min_items"`
	MaxItems   *int                `yaml:"max_items"`

	// present records which YAML keys were explicitly authored. It is what
	// lets a ref overlay deliberately replace true with false, a non-empty
	// slice/map with an empty one, or a value with null. Go zero values alone
	// cannot distinguish those cases from an omitted key.
	present map[string]bool `yaml:"-"`
}

type propertyMapping struct {
	Path      []string        `yaml:"path"`
	Wrap      string          `yaml:"wrap"`
	Transform string          `yaml:"transform"` // reversible named transform, e.g. negate or relative_duration
	present   map[string]bool `yaml:"-"`
}

type itemSchema struct {
	Type       string              `yaml:"type"`
	Properties map[string]property `yaml:"properties"`
}

func (i *itemSchema) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("item must be a mapping, got YAML kind %d", node.Kind)
	}
	if _, err := mappingPresence(node, map[string]bool{"type": true, "properties": true}, "itemSchema"); err != nil {
		return err
	}
	type plainItem itemSchema
	var decoded plainItem
	if err := node.Decode(&decoded); err != nil {
		return err
	}
	*i = itemSchema(decoded)
	return nil
}

var propertyYAMLKeys = map[string]bool{
	"type": true, "description": true, "ref": true, "optional": true,
	"required": true, "values": true, "default": true, "min": true,
	"max": true, "min_length": true, "conflicts_with": true,
	"at_least_one_of": true, "requires_value": true, "required_when": true,
	"mapping": true, "item": true, "properties": true, "variants": true,
	"min_items": true, "max_items": true,
}

func (p *property) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("property must be a mapping, got YAML kind %d", node.Kind)
	}
	present, err := mappingPresence(node, propertyYAMLKeys, "property")
	if err != nil {
		return err
	}
	type plainProperty property
	var decoded plainProperty
	if err := node.Decode(&decoded); err != nil {
		return err
	}
	*p = property(decoded)
	p.present = present
	return nil
}

func (m *propertyMapping) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("mapping must be a YAML mapping, got kind %d", node.Kind)
	}
	present, err := mappingPresence(node, map[string]bool{"path": true, "wrap": true, "transform": true}, "mapping")
	if err != nil {
		return err
	}
	type plainMapping propertyMapping
	var decoded plainMapping
	if err := node.Decode(&decoded); err != nil {
		return err
	}
	*m = propertyMapping(decoded)
	m.present = present
	return nil
}

func mappingPresence(node *yaml.Node, allowed map[string]bool, kind string) (map[string]bool, error) {
	present := make(map[string]bool, len(node.Content)/2)
	for index := 0; index < len(node.Content); index += 2 {
		key := node.Content[index].Value
		if !allowed[key] {
			return nil, fmt.Errorf("field %q not found in type main.%s", key, kind)
		}
		if present[key] {
			return nil, fmt.Errorf("duplicate %s key %q", kind, key)
		}
		present[key] = true
	}
	return present, nil
}

func (p property) has(key string) bool { return p.present[key] }

func (m propertyMapping) has(key string) bool { return m.present[key] }

// --- load + resolve extends ---------------------------------------------

// loadSchema reads path and recursively merges every `extends` entry's
// properties in first, so a chart-specific property of the same name always
// wins.
//
// Both `extends` and `ref` paths resolve against root (the charts/schemas
// directory), NOT against the referencing file's own directory - that
// matters for fragments inside common/, which refer to sibling common/ files
// the same way a chart schema does.
func loadSchema(root, path string) (*chartSchema, error) {
	loader, err := newSchemaLoader(root)
	if err != nil {
		return nil, err
	}
	// The entry chart path is supplied by the caller and is normally relative
	// to its working directory (for example ../charts/schemas/foo.yml).
	// Extends/ref paths, by contrast, are deliberately relative to the schema
	// root. Resolve only this initial path before handing it to the loader so
	// it cannot be joined to the root a second time.
	initial, err := filepath.Abs(path)
	if err != nil {
		return nil, err
	}
	return loader.load(initial)
}

type schemaLoader struct {
	root       string
	active     map[string]int
	activePath []string
}

func newSchemaLoader(root string) (*schemaLoader, error) {
	absolute, err := filepath.Abs(root)
	if err != nil {
		return nil, fmt.Errorf("resolving schema root %s: %w", root, err)
	}
	canonical, err := filepath.EvalSymlinks(absolute)
	if err != nil {
		return nil, fmt.Errorf("resolving schema root %s: %w", root, err)
	}
	return &schemaLoader{root: canonical, active: map[string]int{}}, nil
}

func (l *schemaLoader) resolve(path string) (string, error) {
	if !filepath.IsAbs(path) {
		path = filepath.Join(l.root, path)
	}
	absolute, err := filepath.Abs(path)
	if err != nil {
		return "", err
	}
	canonical, err := filepath.EvalSymlinks(absolute)
	if err != nil {
		return "", err
	}
	relative, err := filepath.Rel(l.root, canonical)
	if err != nil {
		return "", err
	}
	if relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) || filepath.IsAbs(relative) {
		return "", fmt.Errorf("schema path %q escapes schema root %q", path, l.root)
	}
	return canonical, nil
}

func (l *schemaLoader) load(path string) (*chartSchema, error) {
	canonical, err := l.resolve(path)
	if err != nil {
		return nil, err
	}
	if first, ok := l.active[canonical]; ok {
		cycle := append(append([]string(nil), l.activePath[first:]...), canonical)
		for index := range cycle {
			if relative, relErr := filepath.Rel(l.root, cycle[index]); relErr == nil {
				cycle[index] = filepath.ToSlash(relative)
			}
		}
		return nil, fmt.Errorf("schema reference cycle: %s", strings.Join(cycle, " -> "))
	}
	l.active[canonical] = len(l.activePath)
	l.activePath = append(l.activePath, canonical)
	defer func() {
		delete(l.active, canonical)
		l.activePath = l.activePath[:len(l.activePath)-1]
	}()

	raw, err := os.ReadFile(canonical)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", canonical, err)
	}

	var s chartSchema
	if err := decodeStrictYAML(raw, &s); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", canonical, err)
	}
	if s.Version != supportSchemaVersion {
		return nil, fmt.Errorf("%s: unsupported version %d (want exactly %d)", canonical, s.Version, supportSchemaVersion)
	}

	merged := map[string]property{}
	for _, ext := range s.Extends {
		extSchema, err := l.load(ext)
		if err != nil {
			return nil, fmt.Errorf("%s extends %q: %w", canonical, ext, err)
		}
		for name, p := range extSchema.Properties {
			merged[name] = p
		}
	}
	for name, p := range s.Properties {
		merged[name] = p
	}
	s.Properties = merged

	if err := l.resolveRefs(s.Properties); err != nil {
		return nil, err
	}

	if err := requireDescriptions(canonical, s.Properties, ""); err != nil {
		return nil, err
	}

	if err := requireEnforceableBounds(canonical, s.Properties, ""); err != nil {
		return nil, err
	}
	if err := requireSupportedDSL(canonical, s.Properties, ""); err != nil {
		return nil, err
	}
	if err := requireDistinctMappingPaths(canonical, s.Properties, ""); err != nil {
		return nil, err
	}

	return &s, nil
}

func requireSupportedDSL(schemaPath string, props map[string]property, prefix string) error {
	for _, name := range sortedKeys(props) {
		p := props[name]
		full := prefix + name
		if p.Optional && p.Required {
			return fmt.Errorf("%s: property %q cannot be both optional and required", schemaPath, full)
		}
		if !isSupportedPropertyType(p.Type) {
			return fmt.Errorf("%s: property %q has unsupported type %q", schemaPath, full, p.Type)
		}
		if p.Mapping.Wrap != "" && p.Mapping.Wrap != "array" {
			return fmt.Errorf("%s: property %q has unsupported mapping.wrap %q", schemaPath, full, p.Mapping.Wrap)
		}
		if p.Mapping.Wrap == "array" && !isScalarType(p.Type) {
			return fmt.Errorf("%s: property %q uses mapping.wrap array on non-scalar type %q", schemaPath, full, p.Type)
		}
		if p.Mapping.Wrap != "" && p.Mapping.Transform != "" {
			return fmt.Errorf("%s: property %q cannot combine mapping.wrap and mapping.transform", schemaPath, full)
		}
		switch p.Mapping.Transform {
		case "":
		case "negate":
			if p.Type != "bool" {
				return fmt.Errorf("%s: property %q uses negate on %q, want bool", schemaPath, full, p.Type)
			}
		case "relative_duration":
			if p.Type != "string" {
				return fmt.Errorf("%s: property %q uses relative_duration on %q, want string", schemaPath, full, p.Type)
			}
		default:
			return fmt.Errorf("%s: property %q has unsupported mapping.transform %q", schemaPath, full, p.Mapping.Transform)
		}
		for _, segment := range p.Mapping.Path {
			if segment == "" || segment == "*" {
				return fmt.Errorf("%s: property %q has invalid mapping.path segment %q", schemaPath, full, segment)
			}
		}
		if p.Type == "enum" {
			if len(p.Values) == 0 {
				return fmt.Errorf("%s: enum property %q has no values", schemaPath, full)
			}
			seen := map[string]bool{}
			for _, value := range p.Values {
				if value == "" || seen[value] {
					return fmt.Errorf("%s: enum property %q has empty or duplicate value %q", schemaPath, full, value)
				}
				seen[value] = true
			}
		}
		if err := rejectIrrelevantPropertyFields(schemaPath, full, p); err != nil {
			return err
		}
		if p.MinLength != nil && p.Type != "string" {
			return fmt.Errorf("%s: property %q uses min_length on %q, want string", schemaPath, full, p.Type)
		}
		if p.MinLength != nil && *p.MinLength < 0 {
			return fmt.Errorf("%s: property %q has negative min_length", schemaPath, full)
		}
		if (p.MinItems != nil || p.MaxItems != nil) && p.Type != "list" {
			return fmt.Errorf("%s: property %q uses item bounds on %q, want list", schemaPath, full, p.Type)
		}
		if p.MinItems != nil && (*p.MinItems < 0 || p.MaxItems != nil && *p.MinItems > *p.MaxItems) {
			return fmt.Errorf("%s: property %q has invalid item bounds", schemaPath, full)
		}
		if p.MaxItems != nil && *p.MaxItems < 0 {
			return fmt.Errorf("%s: property %q has negative max_items", schemaPath, full)
		}
		if p.Default != nil {
			if err := validatePropertyDefault(schemaPath, full, p); err != nil {
				return err
			}
		}
		if p.Type == "list" {
			if p.Item == nil || (p.Item.Type == "") == (len(p.Item.Properties) == 0) {
				return fmt.Errorf("%s: list property %q must have exactly one scalar item type or object properties", schemaPath, full)
			}
			if p.Item.Type != "" && p.Item.Type != "string" {
				return fmt.Errorf("%s: list property %q has unsupported scalar item type %q; DSL v1 generates only string scalar lists", schemaPath, full, p.Item.Type)
			}
		}
		if p.Type == "map" && (p.Item == nil || p.Item.Type != "" || len(p.Item.Properties) == 0) {
			return fmt.Errorf("%s: map property %q must have object item properties", schemaPath, full)
		}
		if p.Type == "block" && len(p.Properties) == 0 {
			return fmt.Errorf("%s: block property %q has no properties", schemaPath, full)
		}
		if p.Type == "oneof" && !isGeneratedOneof(p) {
			return fmt.Errorf("%s: oneof property %q has unsupported or ambiguous variants", schemaPath, full)
		}
		seenConflicts := map[string]bool{}
		for _, conflict := range p.ConflictsWith {
			if _, ok := props[conflict]; !ok || conflict == name {
				return fmt.Errorf("%s: property %q conflicts_with unknown/self field %q", schemaPath, full, conflict)
			}
			if seenConflicts[conflict] {
				return fmt.Errorf("%s: property %q has duplicate conflicts_with field %q", schemaPath, full, conflict)
			}
			seenConflicts[conflict] = true
			if !containsPropertyName(props[conflict].ConflictsWith, name) {
				return fmt.Errorf("%s: property %q conflicts_with %q is not reciprocal", schemaPath, full, conflict)
			}
		}
		for _, conditional := range []struct {
			name      string
			condition *valueCondition
		}{{"requires_value", p.RequiresValue}, {"required_when", p.RequiredWhen}} {
			conditionName, condition := conditional.name, conditional.condition
			if condition == nil {
				continue
			}
			target, ok := props[condition.Field]
			if !ok || (target.Type != "string" && target.Type != "enum") || condition.Value == "" {
				return fmt.Errorf("%s: property %q has invalid %s target/value", schemaPath, full, conditionName)
			}
			if target.Type == "enum" && !containsPropertyName(target.Values, condition.Value) {
				return fmt.Errorf("%s: property %q %s value %q is outside %q's enum", schemaPath, full, conditionName, condition.Value, condition.Field)
			}
		}

		children := nestedProperties(p)
		if len(p.AtLeastOneOf) > 0 {
			seenAtLeast := map[string]bool{}
			for _, field := range p.AtLeastOneOf {
				if _, ok := children[field]; !ok {
					return fmt.Errorf("%s: property %q at_least_one_of references unknown field %q", schemaPath, full, field)
				}
				if seenAtLeast[field] {
					return fmt.Errorf("%s: property %q has duplicate at_least_one_of field %q", schemaPath, full, field)
				}
				seenAtLeast[field] = true
			}
		}
		if p.Item != nil {
			if err := requireSupportedDSL(schemaPath, p.Item.Properties, full+".item."); err != nil {
				return err
			}
		}
		if err := requireSupportedDSL(schemaPath, p.Properties, full+"."); err != nil {
			return err
		}
		if err := requireSupportedDSL(schemaPath, p.Variants, full+"."); err != nil {
			return err
		}
	}
	return nil
}

func validatePropertyDefault(schemaPath, name string, prop property) error {
	invalid := func() error {
		return fmt.Errorf("%s: property %q default %#v is invalid for type %q", schemaPath, name, prop.Default, prop.Type)
	}
	switch prop.Type {
	case "string":
		value, ok := prop.Default.(string)
		if !ok || prop.MinLength != nil && len(value) < *prop.MinLength {
			return invalid()
		}
	case "enum":
		value, ok := prop.Default.(string)
		if !ok || !containsPropertyName(prop.Values, value) {
			return invalid()
		}
	case "bool":
		if _, ok := prop.Default.(bool); !ok {
			return invalid()
		}
	case "number":
		value, ok := defaultInt64(prop.Default)
		if !ok || prop.Min != nil && value < int64(*prop.Min) || prop.Max != nil && value > int64(*prop.Max) {
			return invalid()
		}
	case "float":
		if _, ok := defaultFloat64(prop.Default); !ok {
			return invalid()
		}
	default:
		return invalid()
	}
	return nil
}

func defaultInt64(value any) (int64, bool) {
	switch typed := value.(type) {
	case int:
		return int64(typed), true
	case int8:
		return int64(typed), true
	case int16:
		return int64(typed), true
	case int32:
		return int64(typed), true
	case int64:
		return typed, true
	default:
		return 0, false
	}
}

func defaultFloat64(value any) (float64, bool) {
	switch typed := value.(type) {
	case int:
		return float64(typed), true
	case int8:
		return float64(typed), true
	case int16:
		return float64(typed), true
	case int32:
		return float64(typed), true
	case int64:
		return float64(typed), true
	case float32:
		return float64(typed), true
	case float64:
		return typed, true
	default:
		return 0, false
	}
}

func containsPropertyName(values []string, wanted string) bool {
	for _, value := range values {
		if value == wanted {
			return true
		}
	}
	return false
}

func rejectIrrelevantPropertyFields(schemaPath, name string, p property) error {
	allowed := map[string]bool{
		"type": true, "description": true, "ref": true, "optional": true,
		"required": true, "default": true, "conflicts_with": true,
		"requires_value": true, "required_when": true, "mapping": true,
	}
	switch p.Type {
	case "string":
		allowed["min_length"] = true
	case "enum":
		allowed["values"] = true
	case "number":
		allowed["min"], allowed["max"] = true, true
	case "list":
		allowed["item"], allowed["min_items"], allowed["max_items"] = true, true, true
	case "map":
		allowed["item"] = true
	case "block":
		allowed["properties"], allowed["at_least_one_of"] = true, true
	case "oneof":
		allowed["variants"], allowed["at_least_one_of"] = true, true
	}
	for key := range p.present {
		if !allowed[key] {
			return fmt.Errorf("%s: property %q sets %q, which is ignored for type %q", schemaPath, name, key, p.Type)
		}
	}
	return nil
}

func isSupportedPropertyType(propertyType string) bool {
	if isScalarType(propertyType) {
		return true
	}
	switch propertyType {
	case "list", "map", "block", "oneof":
		return true
	default:
		return false
	}
}

func requireDistinctMappingPaths(schemaPath string, props map[string]property, prefix string) error {
	type mappedProperty struct {
		name string
		path []string
	}
	var mapped []mappedProperty
	seenGoNames := map[string]string{}
	for _, name := range sortedKeys(props) {
		p := props[name]
		goName := exportedName(name)
		if prior, exists := seenGoNames[goName]; exists {
			return fmt.Errorf("%s: properties %q and %q collide as generated Go field %q", schemaPath, prefix+prior, prefix+name, goName)
		}
		seenGoNames[goName] = name
		if len(p.Mapping.Path) > 0 {
			for _, existing := range mapped {
				if pathHasPrefix(p.Mapping.Path, existing.path) || pathHasPrefix(existing.path, p.Mapping.Path) {
					return fmt.Errorf("%s: properties %q and %q have duplicate or prefix-colliding mapping paths %v and %v", schemaPath, prefix+existing.name, prefix+name, existing.path, p.Mapping.Path)
				}
			}
			mapped = append(mapped, mappedProperty{name: name, path: p.Mapping.Path})
		}
		if p.Item != nil {
			if err := requireDistinctMappingPaths(schemaPath, p.Item.Properties, prefix+name+".item."); err != nil {
				return err
			}
		}
		if err := requireDistinctMappingPaths(schemaPath, p.Properties, prefix+name+"."); err != nil {
			return err
		}
		for variantName, variant := range p.Variants {
			if variant.Type == "block" {
				if err := requireDistinctMappingPaths(schemaPath, variant.Properties, prefix+name+"."+variantName+"."); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func pathHasPrefix(path, prefix []string) bool {
	if len(prefix) > len(path) {
		return false
	}
	for index := range prefix {
		if path[index] != prefix[index] {
			return false
		}
	}
	return true
}

// requireEnforceableBounds rejects min/max on anything that isn't a `number`,
// where int64validator has nothing to bind them to. Without this a bound on a
// string or a list would parse cleanly and then vanish - the same class of
// silent no-op that KnownFields(true) exists to prevent, just one level deeper.
func requireEnforceableBounds(schemaPath string, props map[string]property, prefix string) error {
	for _, name := range sortedKeys(props) {
		p := props[name]
		full := prefix + name
		if (p.Min != nil || p.Max != nil) && p.Type != "number" {
			return fmt.Errorf("%s: property %q is type %q, but min/max are only enforceable on number", schemaPath, full, p.Type)
		}
		if p.Min != nil && p.Max != nil && *p.Min > *p.Max {
			return fmt.Errorf("%s: property %q has min %d greater than max %d", schemaPath, full, *p.Min, *p.Max)
		}
		if p.Item != nil {
			if err := requireEnforceableBounds(schemaPath, p.Item.Properties, full+".item."); err != nil {
				return err
			}
		}
		if err := requireEnforceableBounds(schemaPath, p.Properties, full+"."); err != nil {
			return err
		}
		if err := requireEnforceableBounds(schemaPath, p.Variants, full+"."); err != nil {
			return err
		}
	}

	return nil
}

// requireDescriptions fails loudly on any property with no description,
// including nested block/oneof/list-item/map-item properties, so a schema
// author cannot forget one - the same trap that already silently swallowed
// every default/min/max key before this existed. Runs after resolveRefs so a
// property that reaches its shape only through `ref` has already inherited
// its base's description.
func requireDescriptions(schemaPath string, props map[string]property, prefix string) error {
	for _, name := range sortedKeys(props) {
		p := props[name]
		full := prefix + name
		if p.Description == "" {
			return fmt.Errorf("%s: property %q has no description", schemaPath, full)
		}
		if p.Item != nil {
			if err := requireDescriptions(schemaPath, p.Item.Properties, full+".item."); err != nil {
				return err
			}
		}
		if err := requireDescriptions(schemaPath, p.Properties, full+"."); err != nil {
			return err
		}
		if err := requireDescriptions(schemaPath, p.Variants, full+"."); err != nil {
			return err
		}
	}

	return nil
}

// resolveRefs expands every `ref` in place, walking nested item/block/variant
// properties too - the list chart's ref sits three levels down, under
// published_streams.item.properties, not at the schema root.
func (l *schemaLoader) resolveRefs(props map[string]property) error {
	for name, p := range props {
		if p.Ref != "" {
			base, err := l.loadRef(p.Ref)
			if err != nil {
				return fmt.Errorf("resolving ref on %q: %w", name, err)
			}
			p = overlay(base, p)
			props[name] = p
		}

		if p.Item != nil {
			if err := l.resolveRefs(p.Item.Properties); err != nil {
				return err
			}
		}
		if err := l.resolveRefs(p.Properties); err != nil {
			return err
		}
		if err := l.resolveRefs(p.Variants); err != nil {
			return err
		}
	}

	return nil
}

// loadRef reads "<file>#<propertyName>", resolving file against root.
// loadSchema is reused rather than a bare yaml.Unmarshal so a referenced
// file's own extends/refs resolve first - refs can chain.
func (l *schemaLoader) loadRef(ref string) (property, error) {
	file, name, ok := strings.Cut(ref, "#")
	if !ok {
		return property{}, fmt.Errorf("malformed ref %q, want <file>#<propertyName>", ref)
	}

	if file == "" {
		return property{}, fmt.Errorf("malformed ref %q, file is empty", ref)
	}
	refSchema, err := l.load(file)
	if err != nil {
		return property{}, err
	}

	base, ok := refSchema.Properties[name]
	if !ok {
		return property{}, fmt.Errorf("ref %q: no property %q in %s", ref, name, file)
	}

	return base, nil
}

// overlay returns base with each explicitly authored local field taking
// precedence, including false, empty, and null values.
func overlay(base, local property) property {
	out := base
	if local.has("type") {
		out.Type = local.Type
	}
	if local.has("description") {
		out.Description = local.Description
	}
	if local.has("optional") {
		out.Optional = local.Optional
	}
	if local.has("required") {
		out.Required = local.Required
	}
	if local.has("values") {
		out.Values = local.Values
	}
	if local.has("default") {
		out.Default = local.Default
	}
	if local.has("min") {
		out.Min = local.Min
	}
	if local.has("max") {
		out.Max = local.Max
	}
	if local.has("min_length") {
		out.MinLength = local.MinLength
	}
	if local.has("conflicts_with") {
		out.ConflictsWith = local.ConflictsWith
	}
	if local.has("at_least_one_of") {
		out.AtLeastOneOf = local.AtLeastOneOf
	}
	if local.has("requires_value") {
		out.RequiresValue = local.RequiresValue
	}
	if local.has("required_when") {
		out.RequiredWhen = local.RequiredWhen
	}
	if local.has("mapping") {
		out.Mapping = overlayMapping(base.Mapping, local.Mapping)
	}
	if local.has("item") {
		out.Item = local.Item
	}
	if local.has("properties") {
		out.Properties = local.Properties
	}
	if local.has("variants") {
		out.Variants = local.Variants
	}
	if local.has("min_items") {
		out.MinItems = local.MinItems
	}
	if local.has("max_items") {
		out.MaxItems = local.MaxItems
	}
	out.Ref = ""
	out.present = mergePresence(base.present, local.present)

	return out
}

func overlayMapping(base, local propertyMapping) propertyMapping {
	out := base
	if local.has("path") {
		out.Path = local.Path
	}
	if local.has("wrap") {
		out.Wrap = local.Wrap
	}
	if local.has("transform") {
		out.Transform = local.Transform
	}
	out.present = mergePresence(base.present, local.present)
	return out
}

func mergePresence(base, local map[string]bool) map[string]bool {
	result := make(map[string]bool, len(base)+len(local))
	for key := range base {
		result[key] = true
	}
	for key := range local {
		result[key] = true
	}
	return result
}

