type generationOptions struct {
	SchemasDir           string
	OutDir               string
	PackageName          string
	BridgePath           string
	LegacyGeneratedPaths []string
	BridgePackage        string
	ChartsImport         string
	Check                bool
}

func runGeneration(options generationOptions) error {
	paths, err := filepath.Glob(filepath.Join(options.SchemasDir, "*.yml"))
	if err != nil {
		return err
	}
	sort.Strings(paths)
	actualFiles := make([]string, len(paths))
	for index, path := range paths {
		actualFiles[index] = filepath.Base(path)
	}
	if strings.Join(actualFiles, "\n") != strings.Join(expectedChartFiles, "\n") {
		return fmt.Errorf("chart schema set is %v; want exactly %v", actualFiles, expectedChartFiles)
	}

	expected := map[string][]byte{}
	charts := make([]chartInfo, 0, len(paths))
	for _, path := range paths {
		source, info, chartErr := generateChart(path, options.PackageName)
		if chartErr != nil {
			return chartErr
		}
		if info.Type != strings.TrimSuffix(filepath.Base(path), ".yml") {
			return fmt.Errorf("%s: type %q must exactly match filename", path, info.Type)
		}
		charts = append(charts, info)
		expected[filepath.Join(options.OutDir, info.Type+"_generated.go")] = []byte(source)
	}
	sort.Slice(charts, func(i, j int) bool { return charts[i].Type < charts[j].Type })
	content, err := generateContentAggregate(charts, options.PackageName)
	if err != nil {
		return err
	}
	expected[filepath.Join(options.OutDir, "content_generated.go")] = []byte(content)
	contracts, err := loadContracts(filepath.Join(options.SchemasDir, "elements"), charts)
	if err != nil {
		return err
	}
	if witnessErr := validateMappingWitnesses(paths, options.SchemasDir, contracts); witnessErr != nil {
		return witnessErr
	}
	contractSource, err := generateContractRegistry(charts, contracts, options.PackageName)
	if err != nil {
		return err
	}
	expected[filepath.Join(options.OutDir, "contract_generated.go")] = []byte(contractSource)
	bridge, err := generateParentBridge(charts, options.BridgePackage, options.ChartsImport)
	if err != nil {
		return err
	}
	expected[options.BridgePath] = []byte(bridge)

	stale, err := obsoleteGeneratedFiles(options.OutDir, expected)
	if err != nil {
		return err
	}
	bridgeDirectory := filepath.Dir(options.BridgePath)
	if filepath.Clean(bridgeDirectory) != filepath.Clean(options.OutDir) {
		parentStale, parentErr := obsoleteGeneratedFiles(bridgeDirectory, expected)
		if parentErr != nil {
			return parentErr
		}
		stale = append(stale, parentStale...)
	}
	legacyStale, err := obsoleteGeneratedPaths(options.LegacyGeneratedPaths, expected)
	if err != nil {
		return err
	}
	stale = append(stale, legacyStale...)
	stale = uniqueSortedPaths(stale)
	if options.Check {
		var problems []string
		for path, want := range expected {
			got, readErr := os.ReadFile(path)
			switch {
			case os.IsNotExist(readErr):
				problems = append(problems, "missing: "+path)
			case readErr != nil:
				return readErr
			case !bytes.Equal(got, want):
				problems = append(problems, "changed: "+path)
			}
		}
		for _, path := range stale {
			problems = append(problems, "obsolete: "+path)
		}
		sort.Strings(problems)
		if len(problems) > 0 {
			return fmt.Errorf("generated chart code is stale:\n  %s\nrun `go run ./%s -mode=write`", strings.Join(problems, "\n  "), chartGeneratorPath)
		}
		return nil
	}

	for path, contents := range expected {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, contents, 0o600); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	for _, path := range stale {
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("removing obsolete generated file %s: %w", path, err)
		}
	}
	return nil
}

func obsoleteGeneratedFiles(outDir string, expected map[string][]byte) ([]string, error) {
	entries, err := os.ReadDir(outDir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var obsolete []string
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), "_generated.go") {
			continue
		}
		path := filepath.Join(outDir, entry.Name())
		if _, ok := expected[path]; ok {
			continue
		}
		contents, readErr := os.ReadFile(path)
		if readErr != nil {
			return nil, readErr
		}
		if generatedByChartgen(contents) {
			obsolete = append(obsolete, path)
		}
	}
	sort.Strings(obsolete)
	return obsolete, nil
}

func obsoleteGeneratedPaths(paths []string, expected map[string][]byte) ([]string, error) {
	var obsolete []string
	for _, path := range paths {
		if _, ok := expected[path]; ok {
			continue
		}
		contents, err := os.ReadFile(path)
		switch {
		case os.IsNotExist(err):
			continue
		case err != nil:
			return nil, err
		case generatedByChartgen(contents):
			obsolete = append(obsolete, path)
		}
	}
	return uniqueSortedPaths(obsolete), nil
}

func generatedByChartgen(contents []byte) bool {
	return bytes.Contains(contents, []byte(generatedCodeMarker)) ||
		bytes.Contains(contents, []byte(legacyGeneratedCodeMarker))
}

func uniqueSortedPaths(paths []string) []string {
	sort.Strings(paths)
	unique := paths[:0]
	for _, path := range paths {
		if len(unique) == 0 || unique[len(unique)-1] != path {
			unique = append(unique, path)
		}
	}
	return unique
}

